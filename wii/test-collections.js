const fs = require('fs'), vm = require('vm'), assert = require('assert');
vm.runInThisContext(fs.readFileSync(require('path').join(__dirname, '../content/handlers/javascript/duktape/generics.js'), 'utf8'));
const list = NetSurf.makeListProxy({length: 2, item: i => ['first', 'second'][i] || null});
assert.strictEqual(list[0], 'first');
assert.strictEqual(list['1'], 'second');
assert.strictEqual(list[2], undefined);
assert.strictEqual('0' in list, true);
assert.strictEqual('2' in list, false);
assert.strictEqual(list['01'], undefined);
console.log('PASS: collection indexing');
const styleTarget = {cssText: 'color:red; background-image:url("a;b"); visibility:hidden !important'};
const style = NetSurf.makeStyleProxy(styleTarget);
assert.strictEqual(style.backgroundImage, 'url("a;b")');
assert.strictEqual(style.getPropertyPriority('visibility'), 'important');
style.visibility = 'visible';
assert.strictEqual(style.visibility, 'visible');
assert.strictEqual(style.getPropertyPriority('visibility'), '');
assert.strictEqual(style.backgroundImage, 'url("a;b")');
styleTarget.cssText = 'width: 20px; /* comment; */ height: 10px';
assert.strictEqual(style.width, '20px');
assert.strictEqual(style.height, '10px');
style.display = 'none';
assert.ok(/display: none;/.test(styleTarget.cssText));
assert.strictEqual(style.removeProperty('width'), '20px');
assert.strictEqual(style.width, '');
assert.strictEqual('transform' in style, false);
console.log('PASS: live inline style proxy');
